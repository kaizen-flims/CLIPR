package com.clipr.app.core.model

import kotlinx.serialization.Serializable

/**
 * Normalized UV bounding box [0.0f .. 1.0f] representing a crop region within a source video frame.
 */
@Serializable
data class NormalizedCropRect(
    val left: Float,
    val top: Float,
    val right: Float,
    val bottom: Float
) {
    val width: Float
        get() = (right - left).coerceIn(0.05f, 1.0f)

    val height: Float
        get() = (bottom - top).coerceIn(0.05f, 1.0f)

    val centerX: Float
        get() = (left + right) * 0.5f

    val centerY: Float
        get() = (top + bottom) * 0.5f

    /**
     * Pans the crop box horizontally and vertically while keeping it strictly inside [0.0f .. 1.0f].
     */
    fun panBy(deltaX: Float, deltaY: Float): NormalizedCropRect {
        val w = width
        val h = height
        val newLeft = (left + deltaX).coerceIn(0f, 1f - w)
        val newTop = (top + deltaY).coerceIn(0f, 1f - h)
        return NormalizedCropRect(
            left = newLeft,
            top = newTop,
            right = (newLeft + w).coerceAtMost(1f),
            bottom = (newTop + h).coerceAtMost(1f)
        )
    }

    /**
     * Zooms the crop box around its current center point (`zoomFactor > 1.0f` zooms in).
     */
    fun zoom(zoomFactor: Float): NormalizedCropRect {
        val clampedZoom = zoomFactor.coerceIn(0.5f, 3.0f)
        val newW = (width / clampedZoom).coerceIn(0.10f, 1.0f)
        val newH = (height / clampedZoom).coerceIn(0.10f, 1.0f)
        val cx = centerX
        val cy = centerY
        val newLeft = (cx - newW * 0.5f).coerceIn(0f, 1f - newW)
        val newTop = (cy - newH * 0.5f).coerceIn(0f, 1f - newH)
        return NormalizedCropRect(
            left = newLeft,
            top = newTop,
            right = newLeft + newW,
            bottom = newTop + newH
        )
    }

    companion object {
        /** Default upper-left webcam overlay crop in a 16:9 stream. */
        val DEFAULT_FACECAM_CORNER = NormalizedCropRect(
            left = 0.02f,
            top = 0.04f,
            right = 0.28f,
            bottom = 0.36f
        )

        /** Default center action crop in a 16:9 gameplay recording. */
        val DEFAULT_GAMEPLAY_CENTER = NormalizedCropRect(
            left = 0.22f,
            top = 0.0f,
            right = 0.78f,
            bottom = 1.0f
        )

        /** Default centered 9:16 portrait crop inside a 16:9 frame. */
        val DEFAULT_PORTRAIT_9_16 = NormalizedCropRect(
            left = 0.34f,
            top = 0.0f,
            right = 0.66f,
            bottom = 1.0f
        )

        /** Full uncropped frame [0..1, 0..1]. */
        val FULL_FRAME = NormalizedCropRect(0f, 0f, 1f, 1f)
    }
}

/**
 * Word-level timestamp entry generated by Whisper or Gemini audio alignment (Section 06).
 */
@Serializable
data class SubtitleWordTiming(
    val wordIndex: Int,
    val word: String,
    val relativeStartMs: Long,
    val relativeEndMs: Long,
    val confidence: Float = 0.96f
)

/**
 * Group of 3-5 consecutive words displayed together on the 9:16 canvas with active word highlighting.
 */
data class SubtitlePhraseGroup(
    val groupIndex: Int,
    val startMs: Long,
    val endMs: Long,
    val words: List<SubtitleWordTiming>,
    val activeWordIndexInGroup: Int
)

/**
 * Complete user-customizable subtitle configuration (Section 06: Subtitle engine).
 */
@Serializable
data class SubtitleCustomConfig(
    val preset: SubtitleStylePreset = SubtitleStylePreset.SIGNAL_PUNCH,
    val fontSizeSp: Int = 24,
    val verticalPositionRatio: Float = 0.68f,
    val activeWordColorHex: Long = CliprBrandConfig.SIGNAL_RED_ARGB,
    val baseWordColorHex: Long = CliprBrandConfig.PORCELAIN_WHITE_ARGB,
    val outlineColorHex: Long = CliprBrandConfig.OBSIDIAN_BLACK_ARGB,
    val outlineStrokeWidthPx: Float = 4f,
    val showBackgroundBox: Boolean = true,
    val animatedWordHighlightEnabled: Boolean = true,
    val wordsPerGroup: Int = 4
)
